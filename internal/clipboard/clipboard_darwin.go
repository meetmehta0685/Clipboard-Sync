import "C"

import (
	"errors"
	"unsafe"
)

type darwinClipboard struct{}

// System returns the macOS pasteboard.
func System() (Clipboard, error) { return darwinClipboard{}, nil }

func (darwinClipboard) ChangeCount() int64 { return int64(C.cs_change_count()) }

func (darwinClipboard) Read() (Content, error) {
	concealed := C.cs_is_concealed() == 1
	var buf unsafe.Pointer
	var n C.long
	kind := C.cs_read(&buf, &n)
	if kind == 0 {
		return Content{Concealed: concealed}, nil
	}
	data := C.GoBytes(buf, C.int(n))
	C.free(buf)
	switch kind {
	case 1:
		return Content{Type: Text, Data: data, Concealed: concealed}, nil
	case 3:
		png, err := NormalizeImage(data)
		if err != nil {
			return Content{}, err
		}
		data = png
	}
	return Content{Type: Image, Data: data, Concealed: concealed}, nil
}

func (darwinClipboard) Write(c Content) error {
	kind := C.int(1)
	switch c.Type {
	case Text:
	case Image:
		kind = 2
	default:
		return errors.New("clipboard: can only write text or images")
	}
	if len(c.Data) == 0 {
		return nil
	}
	if C.cs_write(kind, unsafe.Pointer(&c.Data[0]), C.long(len(c.Data))) == 0 {
		return errors.New("clipboard: NSPasteboard write failed")
	}
	return nil
}
